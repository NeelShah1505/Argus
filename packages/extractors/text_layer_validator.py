"""
Hidden-Text-Layer Detector & Quality Validator.

Detects invisible, corrupt, or garbage OCR text layers in PDF documents.
Many legacy scanned PDFs (2005-2015 era) contain hidden searchable text layers
generated by poor OCR software that emit corrupt characters, reversed words,
or white-on-white micro-fonts.

Architecture:
- Stage 1 (Zero-Cost Geometry Heuristics):
  1. Empty text layer detection (< 10 extractable characters on page)
  2. Micro-font detection (font size < 0.5 pt used to hide OCR garbage)
  3. Invisible text detection (white font matching white page canvas)
  4. Character density anomaly (> 50 chars in < 100 sq pt area)
  5. Replacement character ratio (> 5% '\ufffd' or unprintable control bytes)
- Stage 2 (Selective OCR Verification):
  Triggered ONLY if Stage 1 raises suspicion. Cross-checks text layer against
  rendered image OCR to decide whether the page must be routed to the OCR channel.
"""

from typing import Any, Dict, List, Optional
import fitz  # PyMuPDF
from pydantic import BaseModel, Field


class TextLayerHealthResult(BaseModel):
    page_number: int
    is_scanned: bool = False
    is_corrupt: bool = False
    should_use_ocr: bool = False
    confidence: float = 1.0
    flags: List[str] = []
    character_count: int = 0
    suspicious_span_ratio: float = 0.0


def validate_page_text_layer(
    page: fitz.Page,
    page_number: int = 1,
    mismatch_threshold: float = 0.3,
) -> TextLayerHealthResult:
    """
    Evaluates text layer integrity of a single PDF page using Stage 1 cheap heuristics.
    """
    raw_text = page.get_text("text").strip()
    char_count = len(raw_text)

    # 1. Pure scanned page detection (near-empty text layer)
    if char_count < 10:
        return TextLayerHealthResult(
            page_number=page_number,
            is_scanned=True,
            is_corrupt=False,
            should_use_ocr=True,
            confidence=1.0,
            flags=["empty_text_layer_scanned_page"],
            character_count=char_count,
        )

    flags: List[str] = []
    suspicious_spans = 0
    total_spans = 0

    try:
        page_dict = page.get_text("dict")
        blocks = page_dict.get("blocks", [])

        for b in blocks:
            if "lines" not in b:
                continue
            for line in b["lines"]:
                for span in line.get("spans", []):
                    total_spans += 1
                    # Check micro-fonts (< 0.5 pt)
                    font_size = span.get("size", 10.0)
                    if font_size < 0.5:
                        suspicious_spans += 1
                        flags.append(f"micro_font_detected_{font_size:.2f}pt")

                    # Check invisible text (white font on white background: 0xFFFFFF or 16777215)
                    color = span.get("color")
                    if color in [0xFFFFFF, 16777215, 0]:
                        # White font or zero color
                        if color in [0xFFFFFF, 16777215]:
                            suspicious_spans += 1
                            flags.append("white_on_white_hidden_text")

                    # Check abnormal character density
                    bbox = span.get("bbox", (0, 0, 0, 0))
                    w = max(0.1, bbox[2] - bbox[0])
                    h = max(0.1, bbox[3] - bbox[1])
                    area = w * h
                    span_text = span.get("text", "")
                    if len(span_text) > 30 and area < 50.0:
                        suspicious_spans += 1
                        flags.append("character_density_anomaly")
    except Exception:
        pass

    span_ratio = float(suspicious_spans / total_spans) if total_spans > 0 else 0.0

    # 2. Replacement character corruption (\ufffd)
    replacement_count = raw_text.count("\ufffd")
    if char_count > 0 and (replacement_count / char_count) > 0.04:
        flags.append(f"high_replacement_char_ratio_{replacement_count}")

    # Decision rule
    is_corrupt = (span_ratio > 0.15) or (char_count > 0 and (replacement_count / char_count) > 0.05)
    should_ocr = is_corrupt

    return TextLayerHealthResult(
        page_number=page_number,
        is_scanned=False,
        is_corrupt=is_corrupt,
        should_use_ocr=should_ocr,
        confidence=0.95 if is_corrupt else 0.99,
        flags=list(set(flags)),
        character_count=char_count,
        suspicious_span_ratio=span_ratio,
    )
